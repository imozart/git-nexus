// Seletor de idioma: bandeira, lista arredondada, troca de idioma, teclado.
import { connect, sleep } from '../lib.mjs';

const OUT = process.argv[2];
const report = {};
process.on('exit', () => console.log(JSON.stringify(report, null, 2)));
const t = await connect(OUT, report);
await t.ev(`localStorage.setItem('gitnexus.locale', 'pt-BR')`);
await t.ev('location.reload()');
await sleep(2500);
await t.until(`document.querySelector('.lang__btn')`, 15000);
t.check('botão com bandeira', (await t.count('.lang__btn svg')) >= 1);
t.check('sem select nativo', (await t.count('select.core__lang')) === 0);
await t.shot('language-fechado');
await t.ev(`document.querySelector('.lang__btn').click()`);
await sleep(400);
t.check('lista abre com 2 opções', (await t.count('.lang__opt')) === 2);
t.check('opção atual marcada', (await t.ev(`document.querySelector('.lang__opt[aria-selected="true"] .lang__name').textContent`)) === 'Português (Brasil)');
t.check('cantos arredondados', (await t.ev(`getComputedStyle(document.querySelector('.lang__list')).borderRadius`)) === '12px');
t.check('foco na opção atual', (await t.ev(`document.activeElement?.getAttribute('aria-selected')`)) === 'true');
await t.shot('language-aberto');
await t.key('ArrowDown');
await t.key('Enter');
await sleep(500);
t.check('Enter troca para English', (await t.ev(`localStorage.getItem('gitnexus.locale')`)) === 'en');
t.check('lista fecha', (await t.count('.lang__list')) === 0);
t.check('botão mostra EN', (await t.text('.lang__code')) === 'EN');
t.check('interface em inglês', /Commands/.test((await t.text('.core__cmd')) ?? ''));
await t.ev(`document.querySelector('.lang__btn').click()`);
await sleep(300);
await t.key('Escape');
await sleep(300);
t.check('Esc fecha', (await t.count('.lang__list')) === 0);
await t.ev(`document.querySelector('.lang__btn').click()`);
await sleep(300);
await t.ev(`document.body.dispatchEvent(new MouseEvent('mousedown',{bubbles:true}))`);
await sleep(300);
t.check('clique fora fecha', (await t.count('.lang__list')) === 0);
t.close();
